"""Production-ready URL feature extraction for phishing detection.

The functions in this module convert raw URLs into numeric features that can be
used directly by deep learning models. The same feature order is used for both
single URL inference and DataFrame batch extraction.
"""

from __future__ import annotations

import re
from collections import Counter
from urllib.parse import urlparse

import numpy as np
import pandas as pd
import tldextract


FEATURE_COLUMNS = [
    "url_length",
    "domain_length",
    "dot_count",
    "hyphen_count",
    "digit_count",
    "https_present",
    "ip_address_present",
    "suspicious_keyword_count",
    "subdomain_count",
    "special_char_count",
    "url_entropy",
]

SUSPICIOUS_KEYWORDS = (
    "account",
    "admin",
    "bank",
    "billing",
    "confirm",
    "free",
    "login",
    "password",
    "payment",
    "secure",
    "signin",
    "support",
    "update",
    "verify",
    "wallet",
    "webscr",
)

IPV4_PATTERN = re.compile(r"^(?:\d{1,3}\.){3}\d{1,3}$")
SPECIAL_CHARACTER_PATTERN = re.compile(r"[^A-Za-z0-9]")
TLD_EXTRACTOR = tldextract.TLDExtract(suffix_list_urls=())


def extract_features(url: str) -> list[float]:
    """Extract a numeric feature vector from one URL.

    Args:
        url: URL string to analyze.

    Returns:
        A list of numeric feature values ordered according to FEATURE_COLUMNS.
    """

    normalized_url = _normalize_url(url)
    parsed_url = urlparse(normalized_url)
    hostname = parsed_url.hostname or ""
    extracted_domain = TLD_EXTRACTOR(normalized_url)
    registered_domain = _registered_domain(extracted_domain)

    feature_map = {
        "url_length": len(normalized_url),
        "domain_length": len(registered_domain),
        "dot_count": normalized_url.count("."),
        "hyphen_count": normalized_url.count("-"),
        "digit_count": sum(character.isdigit() for character in normalized_url),
        "https_present": int(parsed_url.scheme.lower() == "https"),
        "ip_address_present": int(_has_ip_address(hostname)),
        "suspicious_keyword_count": _count_suspicious_keywords(normalized_url),
        "subdomain_count": _count_subdomains(extracted_domain.subdomain),
        "special_char_count": len(SPECIAL_CHARACTER_PATTERN.findall(normalized_url)),
        "url_entropy": _calculate_entropy(normalized_url),
    }

    return [float(feature_map[column]) for column in FEATURE_COLUMNS]


def extract_dataframe_features(df: pd.DataFrame) -> pd.DataFrame:
    """Extract URL features for every row in a DataFrame.

    The function looks for a column named url by default. If url is not present,
    it uses the first column as a practical fallback for one-column datasets.

    Args:
        df: DataFrame containing a URL column.

    Returns:
        DataFrame containing only numeric model-ready feature columns.
    """

    if df.empty:
        return pd.DataFrame(columns=FEATURE_COLUMNS, dtype=float)

    url_column = "url" if "url" in df.columns else df.columns[0]
    feature_rows = [extract_features(url) for url in df[url_column].fillna("").astype(str)]
    return pd.DataFrame(feature_rows, columns=FEATURE_COLUMNS, dtype=float)


def _normalize_url(url: str) -> str:
    """Normalize raw URL input before parsing and feature extraction."""

    cleaned_url = str(url).strip()
    if not cleaned_url:
        return ""
    if cleaned_url.startswith(("http://", "https://")):
        return cleaned_url
    return f"http://{cleaned_url}"


def _registered_domain(extracted_domain: tldextract.ExtractResult) -> str:
    """Return the domain plus suffix, excluding subdomains."""

    if not extracted_domain.domain:
        return ""
    if not extracted_domain.suffix:
        return extracted_domain.domain
    return f"{extracted_domain.domain}.{extracted_domain.suffix}"


def _has_ip_address(hostname: str) -> bool:
    """Return True when the hostname is an IPv4 address."""

    if not IPV4_PATTERN.fullmatch(hostname):
        return False

    # Ensure each IPv4 octet is in the valid range instead of only matching shape.
    octets = hostname.split(".")
    return all(0 <= int(octet) <= 255 for octet in octets)


def _count_suspicious_keywords(url: str) -> int:
    """Count phishing-related words in the URL."""

    lowered_url = url.lower()
    return sum(1 for keyword in SUSPICIOUS_KEYWORDS if keyword in lowered_url)


def _count_subdomains(subdomain: str) -> int:
    """Count subdomain levels returned by tldextract."""

    if not subdomain:
        return 0
    return len([part for part in subdomain.split(".") if part])


def _calculate_entropy(value: str) -> float:
    """Calculate Shannon entropy for the URL string.

    Entropy helps identify random-looking URLs that may be generated by phishing
    kits or disposable campaign infrastructure.
    """

    if not value:
        return 0.0

    character_counts = Counter(value)
    probabilities = np.array(list(character_counts.values()), dtype=float) / len(value)
    entropy = -np.sum(probabilities * np.log2(probabilities))
    return float(round(entropy, 6))
